"""Self-verifying tests for check_default_invariance.py.

Run directly:

    python3 src/build/test_check_default_invariance.py

The check compares two real configured trees in CI, where an equivalence it wrongly reports would pass
silently. These tests plant small trees that differ in exactly one way each, and require every real
difference to be reported and every allowed one to be ignored.

Exits non-zero if any check fails.
"""

import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(HERE, "check_default_invariance.py")

FAILURES = []

NINJA = """\
rule CUSTOM_COMMAND
  command = $COMMAND

build RV_DEPS_ZLIB-install: CUSTOM_COMMAND
  COMMAND = cd {build}/RV_DEPS_ZLIB/build && cmake --install . --prefix {build}/RV_DEPS_ZLIB/install

build build.ninja: RERUN_CMAKE | {source}/CMakeLists.txt {source}/cmake/macros/rv_find_dependency.cmake{extra_input}

build {source}/CMakeLists.txt {source}/cmake/macros/rv_find_dependency.cmake{extra_input}: phony

build stage/lib/libz.dylib: CUSTOM_COMMAND
  COMMAND = cmake -E copy {build}/RV_DEPS_ZLIB/install/lib/libz.dylib {build}/stage/lib/libz.dylib -DGIT_HEAD=\\"{commit}\\"
"""

INSTALL = """\
if(CMAKE_INSTALL_COMPONENT STREQUAL "Unspecified" OR NOT CMAKE_INSTALL_COMPONENT)
  SET(RV_STAGE_LIB_DIR {build}/stage/lib)
endif()

{forwarded}"""

VCXPROJ = """\
<Project>
  <PropertyGroup><ProjectGuid>{guid}</ProjectGuid></PropertyGroup>
  <CustomBuild Include="{source}/CMakeLists.txt">
    <AdditionalInputs>{source}/cmake/macros/rv_find_dependency.cmake{extra_input}</AdditionalInputs>
  </CustomBuild>
  <ItemDefinitionGroup><Command>cmake --install . --prefix {build}/RV_DEPS_ZLIB/install</Command></ItemDefinitionGroup>
</Project>
"""


def check(description: str, condition: bool, detail: str = "") -> None:
    if condition:
        print(f"  ok   {description}")
    else:
        print(f"  FAIL {description}{(': ' + detail) if detail else ''}")
        FAILURES.append(description)


def write(path: str, content: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(content)


def plant(
    root: str,
    name: str,
    *,
    commit: str = "aaaaaaaa",
    extra_input: str = "",
    forwarded: str = "",
    cache_extra: str = "",
    install_prefix: str = "install",
    generator: str = "ninja",
    guid: str = "{11111111-2222-3333-4444-555555555555}",
) -> str:
    """A configured tree in <root>/<name>, with its source directory beside its build directory."""
    source = os.path.join(root, name)
    build = os.path.join(source, "_build")
    values = {"source": source, "build": build, "commit": commit, "extra_input": extra_input}
    if generator == "ninja":
        write(os.path.join(build, "build.ninja"), NINJA.format(**values).replace("/install", f"/{install_prefix}"))
        write(os.path.join(build, "CMakeFiles", "rules.ninja"), "rule RERUN_CMAKE\n  command = cmake\n")
    else:
        write(
            os.path.join(build, "RvCommon.vcxproj"),
            VCXPROJ.format(guid=guid, **values).replace("/install<", f"/{install_prefix}<"),
        )
        write(os.path.join(build, "ZERO_CHECK.vcxproj"), f"<Project>{extra_input}</Project>\n")
    write(os.path.join(build, "cmake", "install", "cmake_install.cmake"), INSTALL.format(forwarded=forwarded, **values))
    write(
        os.path.join(build, "cmake", "dependencies", "RV_DEPS_ZLIB-prefix", "tmp", "RV_DEPS_ZLIB-cfgcmd.txt"),
        f"cmd='cmake;-DCMAKE_INSTALL_PREFIX={build}/RV_DEPS_ZLIB/{install_prefix}'\n",
    )
    # A fetched source tree is not generated by this configure and must not be compared.
    write(os.path.join(build, "RV_DEPS_ZLIB", "src", "CMakeLists.txt"), f"# {name}\n")
    write(
        os.path.join(build, "CMakeCache.txt"),
        f"CMAKE_HOME_DIRECTORY:INTERNAL={source}\n"
        f"CMAKE_CACHEFILE_DIR:INTERNAL={build}\n"
        f"RV_GIT_COMMIT_SHORT_HASH:STRING={commit}\n"
        f"RV_DEPS_BASE_DIR:STRING={build}\n"
        f"RV_VFX_PLATFORM:STRING=CY2025\n" + cache_extra,
    )
    return build


def run(baseline: str, candidate: str):
    result = subprocess.run([sys.executable, SCRIPT, baseline, candidate], capture_output=True, text=True)
    return result.returncode, result.stdout + result.stderr


FORWARDED_IDENTITY = """\
if(CMAKE_INSTALL_COMPONENT STREQUAL "Unspecified" OR NOT CMAKE_INSTALL_COMPONENT)
  SET(RV_BUILD_IDENTITY_HASH sha256:0123)
endif()

"""

FORWARDED_OTHER = """\
if(CMAKE_INSTALL_COMPONENT STREQUAL "Unspecified" OR NOT CMAKE_INSTALL_COMPONENT)
  SET(RV_SOMETHING_ELSE ON)
endif()

"""


def scenario(description: str, expect_equal: bool, expect_text: str = "", **candidate) -> None:
    with tempfile.TemporaryDirectory() as root:
        generator = candidate.pop("generator", "ninja")
        baseline = plant(root, "baseline", generator=generator)
        tree = plant(root, "candidate", generator=generator, **candidate)
        code, output = run(baseline, tree)
        if expect_equal:
            check(description, code == 0, output[-800:])
        else:
            check(description, code == 1 and expect_text in output, output[-800:])


def main() -> int:
    print("check_default_invariance.py")
    scenario("an identical configure from another checkout and commit is equivalent", True, commit="bbbbbbbb")
    scenario(
        "new CMake input files that only re-run CMake are ignored", True, extra_input=" <x>/rv_build_identity.cmake"
    )
    scenario(
        "this change's variables forwarded into the install script are ignored", True, forwarded=FORWARDED_IDENTITY
    )
    scenario(
        "this change's own cache entries are allowed",
        True,
        cache_extra="RV_BUILD_IDENTITY:BOOL=ON\nRV_DEPS_STORE:STRING=\nRV_DEPS_STORE_ELIGIBLE:STRING=default\n",
    )
    scenario(
        "a moved dependency install directory is reported", False, "build.ninja differs", install_prefix="elsewhere"
    )
    scenario(
        "a changed ExternalProject command is reported",
        False,
        "RV_DEPS_ZLIB-cfgcmd.txt differs",
        install_prefix="moved",
    )
    scenario(
        "another variable forwarded into the install script is reported",
        False,
        "cmake_install.cmake",
        forwarded=FORWARDED_OTHER,
    )
    scenario("an unknown cache entry is reported", False, "RV_SOMETHING_NEW", cache_extra="RV_SOMETHING_NEW:BOOL=ON\n")
    scenario(
        "a changed shared cache entry is reported",
        False,
        "RV_VFX_PLATFORM",
        cache_extra="RV_VFX_PLATFORM:STRING=CY2026\n",
    )

    with tempfile.TemporaryDirectory() as root:
        # CI installs Qt inside the checkout that is configured first, and the baseline configure uses the same Qt.
        qt = f"RV_DEPS_QT_LOCATION:PATH={os.path.join(root, 'candidate', 'deps', 'Qt')}\n"
        code, output = run(plant(root, "baseline", cache_extra=qt), plant(root, "candidate", cache_extra=qt))
        check("an input inside one checkout used by both trees is equivalent", code == 0, output[-800:])

    print("Visual Studio")
    scenario(
        "project GUIDs derived from paths and regeneration inputs are ignored",
        True,
        generator="vs",
        guid="{99999999-8888-7777-6666-555555555555}",
        extra_input=" <x>/rv_build_identity.cmake",
    )
    scenario(
        "a moved dependency install directory is reported",
        False,
        "RvCommon.vcxproj differs",
        generator="vs",
        install_prefix="x",
    )

    if FAILURES:
        print(f"\n{len(FAILURES)} check(s) failed:")
        for failure in FAILURES:
            print(f"  - {failure}")
        return 1
    print("\nall default invariance checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
